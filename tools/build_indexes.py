r"""build_indexes.py - regenerate knowledge\INDEX.md and lessons\INDEX.md from the files on disk.

What it does: writes two one-line-per-entry indexes that CLAUDE.md can import cheaply.
  knowledge\INDEX.md: one line per category folder (NN-name): its path and the list of note files.
  lessons\INDEX.md:   one line per lesson file: its path and first heading.
Inputs: the knowledge\ and lessons\ folders of this repository (or --root). Outputs: the two INDEX.md files.
Idempotent: running it twice gives the same files.
Usage: .venv\Scripts\python.exe tools\build_indexes.py [--root DIR]
Example: .venv\Scripts\python.exe tools\build_indexes.py
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mm_config  # noqa: E402

BRAIN = str(mm_config.repo_root())


def first_heading(path: str) -> str:
    try:
        for line in open(path, encoding="utf-8", errors="replace"):
            if line.startswith("# "):
                return line[2:].strip()
    except Exception:  # noqa: BLE001
        pass
    return os.path.basename(path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=BRAIN, help="repository folder that holds knowledge\\ and lessons\\ (default: this repository)")
    a = ap.parse_args(argv)
    root = a.root
    kroot = os.path.join(root, "knowledge")
    lines = ["# Knowledge index (generated by tools\\build_indexes.py - one line per category; open the category index.md for notes)", ""]
    for cat in sorted(d for d in os.listdir(kroot) if os.path.isdir(os.path.join(kroot, d)) and re.match(r"\d\d-", d)):
        notes = sorted(os.path.basename(p) for p in glob.glob(os.path.join(kroot, cat, "*.md")) if not p.lower().endswith("index.md"))
        lines.append(f"- `knowledge/{cat}/` - {len(notes)} note(s)" + (": " + ", ".join(notes) if notes else " (empty)"))
    open(os.path.join(kroot, "INDEX.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    lroot = os.path.join(root, "lessons")
    llines = ["# Lessons index (generated; one line per post-mortem - read the file for root cause and rule)", ""]
    for p in sorted(glob.glob(os.path.join(lroot, "*.md"))):
        if p.lower().endswith("index.md"):
            continue
        llines.append(f"- `lessons/{os.path.basename(p)}` - {first_heading(p)}")
    open(os.path.join(lroot, "INDEX.md"), "w", encoding="utf-8", newline="\n").write("\n".join(llines) + "\n")
    print(f"knowledge/INDEX.md: {len(lines) - 2} categories; lessons/INDEX.md: {len(llines) - 2} lessons")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
